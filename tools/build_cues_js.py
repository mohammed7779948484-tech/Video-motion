#!/usr/bin/env python3
"""Emit assets/js/cues.js (window.SYRAZEN) from tools/cues.json so picture and sound share one timing source."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "tools" / "cues.json").read_text())
out = root / "assets" / "js" / "cues.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("/* GENERATED by tools/build_cues_js.py from tools/cues.json - do not edit by hand. */\n"
               "window.SYRAZEN = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n")
print(f"wrote {out.relative_to(root)}")
